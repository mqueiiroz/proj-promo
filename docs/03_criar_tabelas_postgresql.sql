-- Esquema inicial do PostgreSQL. Execute em um banco vazio.
-- Preserva os nomes e os indicadores 0/1 usados pelo Python e pelo PHP.
BEGIN;

CREATE TABLE LOJA (
    ID                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME                  VARCHAR(60)  NOT NULL UNIQUE,
    URL_BASE              VARCHAR(200) NOT NULL,
    MODELO_LINK_AFILIADO  VARCHAR(500),                  -- como o programa monta o link (definir quando aprovado)
    ATIVA                 SMALLINT DEFAULT 1 NOT NULL CHECK (ATIVA IN (0, 1)),
    CRIADO_EM             TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL
);

CREATE TABLE PRODUTO (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOJA_ID         BIGINT NOT NULL REFERENCES LOJA (ID),
    CODIGO_LOJA     VARCHAR(100)  NOT NULL,              -- identificador do produto na loja
    NOME            VARCHAR(300)  NOT NULL,
    CATEGORIA       VARCHAR(30)   NOT NULL,              -- GPU, SSD, RAM, CPU...
    URL_ORIGINAL    VARCHAR(1000) NOT NULL,
    URL_AFILIADO    VARCHAR(1500),
    IMAGEM_URL      VARCHAR(1000),
    PRECO_ATUAL     NUMERIC(10, 2),
    PRECO_ORIGINAL  NUMERIC(10, 2),
    DISPONIVEL      SMALLINT DEFAULT 1 NOT NULL CHECK (DISPONIVEL IN (0, 1)),
    VISTO_EM        TIMESTAMP,                            -- última coleta em que o produto apareceu
    CRIADO_EM       TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    ATUALIZADO_EM   TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    PROMOCAO_DESDE  TIMESTAMP,
    CONSTRAINT UQ_PRODUTO_LOJA_CODIGO UNIQUE (LOJA_ID, CODIGO_LOJA)
);

-- Só recebe registro quando o preço muda (RF2).
CREATE TABLE HISTORICO_PRECO (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUTO_ID      BIGINT NOT NULL REFERENCES PRODUTO (ID),
    PRECO           NUMERIC(10, 2) NOT NULL,
    PRECO_ORIGINAL  NUMERIC(10, 2),
    COLETADO_EM     TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL
);

CREATE INDEX IDX_HISTORICO_PRODUTO_DATA ON HISTORICO_PRECO (PRODUTO_ID, COLETADO_EM);

-- Registro de eventos da coleta; alimenta o painel de monitoramento.
CREATE TABLE LOG_COLETA (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOJA_ID     BIGINT NOT NULL REFERENCES LOJA (ID),
    PRODUTO_ID  BIGINT REFERENCES PRODUTO (ID),           -- vazio em eventos da loja inteira
    TIPO        VARCHAR(20) NOT NULL CHECK (TIPO IN
                    ('COLETA_OK', 'COLETA_FALHA', 'PRODUTO_NOVO',
                     'PRECO_ALTERADO', 'ESGOTADO', 'VOLTOU_ESTOQUE')),
    MENSAGEM    VARCHAR(500),
    CRIADO_EM   TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL
);

CREATE INDEX IDX_LOG_LOJA_DATA ON LOG_COLETA (LOJA_ID, CRIADO_EM);

-- Login do painel de monitoramento. Guardar apenas o hash da senha, nunca a senha.
CREATE TABLE USUARIO (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL       VARCHAR(200) NOT NULL UNIQUE,
    SENHA_HASH  VARCHAR(255) NOT NULL,
    CRIADO_EM   TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL
);

-- Promoções ativas com o desconto calculado (o desconto não é guardado, é derivado).
CREATE OR REPLACE VIEW V_PROMOCOES_ATIVAS AS
WITH precos_recentes AS (
    SELECT ID, PRODUTO_ID, PRECO, COLETADO_EM,
           ROW_NUMBER() OVER (PARTITION BY PRODUTO_ID ORDER BY COLETADO_EM DESC, ID DESC) AS posicao
    FROM HISTORICO_PRECO
),
referencias AS (
    SELECT p.ID, l.NOME AS LOJA, p.NOME, p.CATEGORIA, p.PRECO_ATUAL, p.PRECO_ORIGINAL,
           p.URL_AFILIADO, p.IMAGEM_URL,
           CAST(COALESCE(p.PRECO_ORIGINAL, (
               SELECT MIN(h.PRECO)
               FROM HISTORICO_PRECO h
               WHERE h.PRODUTO_ID = atual.PRODUTO_ID
                 AND h.COLETADO_EM >= atual.COLETADO_EM - INTERVAL '7' DAY
                 AND (h.COLETADO_EM < atual.COLETADO_EM
                      OR (h.COLETADO_EM = atual.COLETADO_EM AND h.ID < atual.ID))
           )) AS NUMERIC(10, 2)) AS PRECO_REFERENCIA,
           CASE WHEN p.PRECO_ORIGINAL IS NULL THEN 'historico' ELSE 'loja' END AS ORIGEM_REFERENCIA,
           CASE WHEN p.PRECO_ORIGINAL IS NULL THEN atual.COLETADO_EM
                ELSE p.PROMOCAO_DESDE END AS PROMOCAO_DESDE
    FROM PRODUTO p
    JOIN LOJA l ON l.ID = p.LOJA_ID
    LEFT JOIN precos_recentes atual ON p.PRECO_ORIGINAL IS NULL AND atual.PRODUTO_ID = p.ID
         AND atual.posicao = 1 AND atual.PRECO = p.PRECO_ATUAL
    WHERE p.DISPONIVEL = 1
)
SELECT ID, LOJA, NOME, CATEGORIA, PRECO_ATUAL, PRECO_ORIGINAL,
       ROUND((1 - PRECO_ATUAL / NULLIF(PRECO_REFERENCIA, 0)) * 100) AS DESCONTO_PCT,
       URL_AFILIADO, IMAGEM_URL, PRECO_REFERENCIA, ORIGEM_REFERENCIA, PROMOCAO_DESDE
FROM referencias
WHERE PRECO_ATUAL > 0
  AND PRECO_REFERENCIA > PRECO_ATUAL
  AND (ORIGEM_REFERENCIA = 'loja' OR PRECO_ATUAL * 100 <= PRECO_REFERENCIA * 99);


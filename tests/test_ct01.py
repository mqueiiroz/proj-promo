@dataclass
class Resposta:
    status: int
    cabecalhos: object
    texto: str

    def json(self):
        return json.loads(self.texto)


class AplicacaoCt01:
    def __init__(self, pasta, engine_postgres=None, ambiente_postgres=None):
        self.pasta = pasta
        self.engine_postgres = engine_postgres
        self.banco = pasta / "ct01.sqlite"
        self.cgi = shutil.which("php-cgi")
        self.php = shutil.which("php")
        self.node = shutil.which("node")
        assert all((self.cgi, self.php, self.node)), "Instale php, php-cgi e Node.js para executar o CT-01."
        (pasta / "sessoes").mkdir()
        shutil.copytree(RAIZ / "app", pasta / "app")
        shutil.copytree(RAIZ / "web", pasta / "web")
        (pasta / "scripts").mkdir()
        shutil.copyfile(RAIZ / "scripts" / "criar_admin.php", pasta / "scripts" / "criar_admin.php")
        modulo = "pdo_pgsql" if engine_postgres else "pdo_sqlite"
        if engine_postgres is None:
            shutil.copyfile(SUPORTE / "ct01_banco.php", pasta / "app" / "banco.php")
            carregar_esquema(self.banco)
        extensoes = executar([self.php, "-r", 'echo ini_get("extension_dir");']).decode().strip()
        ini = pasta / "php.ini"
        ini.write_text(f'extension_dir="{extensoes}"\nsession.save_path="{pasta / "sessoes"}"\n', encoding="utf-8")
        self.ambiente_php = {**os.environ, **(ambiente_postgres or {}), "PHPRC": str(ini)}
        padrao_modulo = rf"^{modulo}\r?$".encode()
        modulos = executar([self.cgi, "-m"], env=self.ambiente_php)
        if not re.search(padrao_modulo, modulos, re.MULTILINE):
            with ini.open("a", encoding="utf-8") as arquivo:
                arquivo.write(f"extension={modulo}\n")
        assert re.search(padrao_modulo, executar([self.cgi, "-m"], env=self.ambiente_php), re.MULTILINE), (
            f"Habilite a extensão {modulo} no PHP."
        )
        self.cookie = ""

    def requisitar(self, rota, formulario=None):
        corpo = b"" if formulario is None else urlencode(formulario).encode("ascii")
        url = urlsplit(rota)
        script = {
            "/api/produtos.php": "web/api/produtos.php",
            "/api/produto.php": "web/api/produto.php",
        }.get(url.path, "app/roteador.php")
        ambiente = {
            **self.ambiente_php,
            "REDIRECT_STATUS": "200",
            "REQUEST_METHOD": "GET" if formulario is None else "POST",
            "REQUEST_URI": rota,
            "QUERY_STRING": url.query,
            "SCRIPT_FILENAME": str(self.pasta / script),
            "CONTENT_TYPE": "application/x-www-form-urlencoded",
            "CONTENT_LENGTH": str(len(corpo)),
            "HTTP_COOKIE": self.cookie,
            "REMOTE_ADDR": "127.0.0.1",
        }
        resposta = executar([self.cgi], cwd=self.pasta, env=ambiente, input=corpo)
        cabecalho, texto = re.split(rb"\r?\n\r?\n", resposta, maxsplit=1)
        cabecalhos = BytesParser().parsebytes(cabecalho)
        for valor in cabecalhos.get_all("Set-Cookie", []):
            cookie = SimpleCookie(valor).get("promo_painel")
            if cookie is not None:
                self.cookie = f"promo_painel={cookie.value}"
        return Resposta(int(cabecalhos.get("Status", "200").split()[0]), cabecalhos, texto.decode("utf-8"))

    def consultar(self, sql):
        if self.engine_postgres is not None:
            with self.engine_postgres.connect() as banco:
                return banco.exec_driver_sql(sql).fetchall()
        with sqlite3.connect(self.banco) as banco:
            return banco.execute(sql).fetchall()

    def renderizar(self, lista, destaque, historico=None):
        executar(
            [self.node, str(SUPORTE / "ct01_home.cjs"), str(self.pasta / "web" / "app.js"),
             str(self.pasta / "web" / "produto.js")],
            input=json.dumps({"dados": lista, "esperado": destaque, "detalhe": historico}).encode(),
        )



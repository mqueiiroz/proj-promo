def entrar_no_painel(app):
    executar(
        [app.php, str(app.pasta / "scripts" / "criar_admin.php"), EMAIL],
        cwd=app.pasta, env=app.ambiente_php, input=(SENHA + "\n").encode(),
    )
    login = app.requisitar("/login")
    token = re.search(r'name="csrf" value="([0-9a-f]{64})"', login.texto)[1]

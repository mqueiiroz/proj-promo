def executar(comando, **opcoes):
    resultado = subprocess.run(comando, capture_output=True, timeout=15, **opcoes)
    assert resultado.returncode == 0, resultado.stderr.decode("utf-8", errors="replace")
    return resultado.stdout


def carregar_esquema(caminho):
    sql = (RAIZ / "docs" / "01_criar_tabelas.sql").read_text(encoding="utf-8")
    sql = sql.replace("NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "INTEGER PRIMARY KEY")
    sql = sql.replace("CREATE OR REPLACE VIEW", "CREATE VIEW")
    sql = sql.replace("PRECO_ATUAL / NULLIF(", "CAST(PRECO_ATUAL AS REAL) / NULLIF(")
    sql = sql.replace("atual.COLETADO_EM - INTERVAL '7' DAY", "DATETIME(atual.COLETADO_EM, '-7 days')")
    # A reflexão no Oracle normaliza identificadores sem aspas para minúsculas.
    sql = sql.rstrip().removesuffix("COMMIT;")
    partes = re.split(r"('(?:[^']|'')*')", sql)
    sql = "".join(parte if indice % 2 else parte.lower() for indice, parte in enumerate(partes))
    with sqlite3.connect(caminho) as banco:
        banco.executescript(sql)



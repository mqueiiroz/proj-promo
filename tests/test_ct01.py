def test_lote_com_falha_e_sucesso_exibe_aviso_sem_alterar_oferta_anterior(aplicacao, monkeypatch):
    app = aplicacao
    coletar_fixture(app, 1899)
    anterior = app.requisitar("/api/produto.php?id=1").json()
    url_gpu = "https://www.kabum.com.br/produto/621163"
    gpu = extrair_produto(gravar_fixture(app.pasta, 2199, "621163").read_text(encoding="utf-8"), url_gpu)
    falhar_ssd = True

    def coletar_categoria(_, categoria, *args):
        if categoria == "SSD":
            return ResultadoCategoria(
                falhas=[{"url": PRODUTO_URL, "erro": "HTTP 503"}] if falhar_ssd else [],
                verificados=[PRODUTO_URL],
            )
        return ResultadoCategoria(produtos=[gpu], verificados=[url_gpu])

    monkeypatch.setattr(coletar.ColetorCategorias, "coletar", coletar_categoria)
    monkeypatch.setattr(coletar.ColetorCategorias, "rever", lambda _, urls: ResultadoCategoria())
    assert coletar.main(["--categorias", "SSD", "GPU"]) == 1
    assert app.requisitar("/api/produto.php?id=1").json() == anterior
    assert app.consultar("SELECT TIPO FROM LOG_COLETA ORDER BY ID DESC LIMIT 2") == [
        ("COLETA_FALHA",), ("COLETA_OK",),
    ]
    entrar_no_painel(app)
    painel = app.requisitar("/painel")
    assert painel.status == 200 and "aviso-coleta" in painel.texto

    falhar_ssd = False
    assert coletar.main(["--categorias", "SSD", "GPU"]) == 0
    painel = app.requisitar("/painel")
    assert painel.status == 200 and "aviso-coleta" not in painel.texto


def test_falha_de_infraestrutura_sem_evento_no_banco_aparece_no_painel(aplicacao, monkeypatch):
    app = aplicacao
    entrar_no_painel(app)

    def banco_indisponivel():
        raise PersistenciaError("Detalhe interno de teste.")

    monkeypatch.setattr(coletar, "criar_engine", banco_indisponivel)
    assert coletar.main([PRODUTO_URL, "--categoria", "SSD"]) == 1
    assert app.consultar("SELECT ID FROM LOG_COLETA") == []
    painel = app.requisitar("/painel")
    assert painel.status == 200 and "Última falha de infraestrutura" in painel.texto
    assert "Detalhe interno de teste" not in painel.texto
    execucao.registrar_log_local("EXECUCAO_OK")
    assert "Última falha de infraestrutura" not in app.requisitar("/painel").texto
